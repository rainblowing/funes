// OKF export — a funes star → an OKF Knowledge Bundle. PLAN-0.2.1 Phase 4 (steps 25-27): moved
// here from twinkling's `ts/src/okf-export.ts`, bumped to spec v0.2, and given a transactional
// promotion so a failed export can no longer leave the previous bundle deleted.
//
// EXPORT-ONLY and non-canonical: funes stays the richer canon and this emits the OKF *floor*. The
// mapping carries every funes key the spec has no home for as an extension key, because OKF asks
// consumers to preserve unknown fields — so a well-behaved consumer keeps the funes superset. It
// is ONE-WAY, not a round-trip: [[wikilinks]] become relative markdown links and index.md files
// are REGENERATED as directory listings, so re-importing a bundle would not reconstruct the vault.
//
// Two properties are worth stating before the code, because both were bought with real failures:
//
//   SCOPE. The bundle may contain only what the INDEX sees — de-indexed is de-exported. funes now
//   reads `star.yaml` `index_scope` itself rather than taking a predicate from a caller, and a
//   tombstoned page (superseded/forgotten) is skipped, so a bundle cannot ship a note recall has
//   already retired.
//
//   PROMOTION. The old exporter called `rmSync(outDir)` and then wrote. Every failure after that
//   line — a secret finding, a full disk, a crash — left the user with no bundle at all, and the
//   secret belt's own remedy was to delete the bundle again. The sequence below never removes the
//   live bundle until a complete, scanned replacement is sitting beside it.
