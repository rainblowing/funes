/** Default bundle home: in-star `out_okf/`, beside the knowledge it distils (ADR-0006). The
 *  eviction to ~/.twinkling was Dropbox-era — no per-folder ignores, so a derived bundle rode every
 *  sync. Syncthing's .stignore ends that; SKIP_DIRS and star.yaml keep the bundle out of the scan
 *  and out of recall. FUNES_OKF_DIR still restores a shared off-vault home, old layout. */
export const okfDefaultOutDir = (vaultRoot: string): string =>
  process.env.FUNES_OKF_DIR
    ? join(process.env.FUNES_OKF_DIR, basename(resolve(vaultRoot)))
    : join(resolve(vaultRoot), "out_okf");

const TMP_RE = /^\.okf-tmp-/;
const BAK_RE = /^\.okf-bak-/;

/** Crash recovery, run under the lock before anything else touches the target. Every combination
 *  the promotion sequence can be interrupted in has a defined outcome:
 *    • a backup with NO target        → the rename that would have restored it never ran: restore it.
 *    • a temp dir                     → the lock is exclusive, so nothing owns it: delete it.
 *    • a backup AND a target          → the target is the newer, complete bundle and WINS; the
 *                                       backup is reported for manual review and never auto-deleted,
 *                                       because "probably stale" is not a reason to delete data. */
function recoverInterrupted(parent: string, name: string): { stranded?: string } {
  const target = join(parent, name);
  let entries: string[];
  try { entries = readdirSync(parent); } catch { return {}; }
  // Prefix-EXACT, not `includes`: sibling bundles live in the same parent, so a target named `a`
  // must not adopt `.okf-bak-abc-…` as its own interrupted backup and restore it over `a`.
  const mine = (prefix: string) => (e: string): boolean => e.startsWith(`${prefix}${name}-`);
  const backups = entries.filter(mine(".okf-bak-")).sort();
  for (const t of entries.filter(mine(".okf-tmp-"))) {
    rmSync(join(parent, t), { recursive: true, force: true });
  }
  if (backups.length === 0) return {};
  if (!existsSync(target)) {
    renameSync(join(parent, backups[backups.length - 1]!), target); // newest wins the restore
    for (const b of backups.slice(0, -1)) rmSync(join(parent, b), { recursive: true, force: true });
    return {};
  }
  return { stranded: join(parent, backups[backups.length - 1]!) };
}

/** Export the star at `vaultRoot` to an OKF bundle at `outDir`, transactionally. */
export async function exportOkf(
  vaultRoot: string,
  outDir = okfDefaultOutDir(vaultRoot),
  opts: OkfExportOpts = {},
): Promise<OkfExportResult> {
  const vaultAbs = resolve(vaultRoot);
  const outAbs = resolve(outDir);
  const parent = dirname(outAbs);
  const name = basename(outAbs);
  const starId = opts.starId ?? null;

  // ONE exclusive lock, held from preflight through cleanup. Keyed on the OUTPUT PATH, so two
  // exports of different stars run concurrently and two exports of the SAME target never do. This
  // reuses funes' own write lock rather than porting a second one: it already records holder pid +
  // token, reclaims a lock whose owner is demonstrably dead (ESRCH only, so an EPERM-on-another-
  // user's-process is never mistaken for death), and refuses to delete a lock reclaimed under it.
  return withWriteLock(outAbs, async () => {
    mkdirSync(parent, { recursive: true });
    const recovered = recoverInterrupted(parent, name);

    assertNotSymlink(outAbs);
    assertSafeOutDir(outAbs, vaultAbs);
    // ADR-0006: an in-vault bundle must be OUTSIDE recall's scope, or the next reindex ingests the
    // bundle's pages as duplicate concepts. Fail closed, exactly like the secret gate. The dir-form
    // probe (`<rel>/`) is the same shape walkMd asks before it descends.
    if (outAbs.startsWith(vaultAbs + sep) && !opts.exclude?.(`${relative(vaultAbs, outAbs)}/`)) {
      throw new Error(
        `okf-export: refusing ${outAbs} — inside the vault and not excluded from index_scope; add ` +
        `"${relative(vaultAbs, outAbs)}/**" to star.yaml memory.index_scope.exclude, or export off-vault (FUNES_OKF_DIR / --out)`,
      );
    }
    assertReplaceableTarget(outAbs, starId);

    const txn = randomBytes(6).toString("hex");
    const tmpAbs = join(parent, `.okf-tmp-${name}-${txn}`);
    rmSync(tmpAbs, { recursive: true, force: true });

    let built: { concepts: number; indexes: number; warnings: string[] };
    try {
      built = buildBundle(vaultAbs, tmpAbs, outAbs, starId, opts.exclude);
    } catch (e) {
      rmSync(tmpAbs, { recursive: true, force: true });
      throw e;
    }

    // Scan the BUILD, before it is anywhere a reader could find it. A failure here leaves the
    // previous bundle exactly as it was, which is the whole reason the sequence is shaped this way.
    const scan = scanBundle(tmpAbs);
    if (scan.regexFindings.length > 0 || scan.gitleaks.length > 0) {
      rmSync(tmpAbs, { recursive: true, force: true });
      const lines = scan.regexFindings.map((f) => `  ${f.file}: ${Object.entries(f.kinds).map(([k, n]) => `${k}×${n}`).join(", ")}`);
      throw new Error(
        `okf-export: ABORTED — secret material in the bundle. Nothing was published and the previous bundle is untouched.\n` +
        (lines.length ? `${lines.join("\n")}\n` : "") +
        (scan.gitleaks.length ? `  gitleaks:\n${scan.gitleaks.map((l) => `    ${l}`).join("\n")}\n` : "") +
        "  Fix the source pages; a bundle exists to be shared, so it cannot ship unscannable.",
      );
    }

    // Promote. Backup first so a crash between the two renames leaves a restorable state, and the
    // backup is deleted only once the target is verifiably in place.
    const bakAbs = join(parent, `.okf-bak-${name}-${Date.now()}-${txn}`);
    const hadTarget = existsSync(outAbs);
    if (hadTarget) renameSync(outAbs, bakAbs);
    try {
      renameSync(tmpAbs, outAbs);
    } catch (e) {
      if (hadTarget) renameSync(bakAbs, outAbs); // put the user's bundle back before reporting
      rmSync(tmpAbs, { recursive: true, force: true });
      throw e;
    }
    if (hadTarget) rmSync(bakAbs, { recursive: true, force: true });

    return {
      ...built,
      outDir: outAbs,
      gitleaksRan: scan.gitleaksRan,
      ...(recovered.stranded ? { strandedBackup: recovered.stranded } : {}),
    };
  }, { timeoutMs: opts.timeoutMs });
}

/** Write the bundle into `buildDir`. `finalAbs` is where it will END UP, and it is excluded from
 *  the walk so a bundle inside the vault can never fold itself in. */
function buildBundle(
  vaultAbs: string,
  buildDir: string,
  finalAbs: string,
  starId: string | null,
  exclude?: (rel: string) => boolean,
): { concepts: number; indexes: number; warnings: string[] } {
  const relPaths = walkPages(vaultAbs, "", new Set([finalAbs, buildDir]), exclude);

  // Read ONCE, then decide. Step 25's tombstone rule needs each page's frontmatter, and so does the
  // mapping — reading in the walk and again here would double the I/O, which is free on a normal
  // filesystem and emphatically not on the Dropbox-backed vaults this estate runs on.
  //
  // ponytail: peak memory is the vault's markdown, which is the same order as the bundle this
  // function is about to write. Stream it in two passes if a star ever outgrows that.
  const sources: Array<{ rel: string; data: Frontmatter; body: string }> = [];
  for (const rel of relPaths) {
    if (RESERVED.has(basename(rel))) continue; // reserved files are REGENERATED, never carried
    const parsed = parseFrontmatter(readFileSync(join(vaultAbs, rel), "utf8"));
    // A tombstoned page (superseded or forgotten) is off the index, so it is off the bundle.
    if (isTombstoned(parsed.data as MemoryMeta)) continue;
    sources.push({ rel, data: parsed.data, body: parsed.body });
  }

  const conceptRels = sources.map((s) => s.rel);
  const pages = new Set(conceptRels);
  const stemIndex = buildStemIndex(conceptRels);

  const dirs = new Set<string>([""]);
  const warnings: string[] = [];
  let concepts = 0;
  for (const { rel, data, body } of sources) {
    const mapped = pageToOkfConcept(data, body, rel, pages, stemIndex);
    warnings.push(...mapped.warnings);
    const dst = join(buildDir, rel);
    mkdirSync(dirname(dst), { recursive: true });
    writeFileSync(dst, mapped.text);
    for (let d = dirname(rel); d !== "." && d !== ""; d = dirname(d)) dirs.add(d);
    concepts++;
  }

  // Reserved files: a plain directory listing per dir. Frontmatter appears ONLY at the bundle root,
  // where it carries the version and the star stamp the replace precondition reads back.
  let indexes = 0;
  for (const d of dirs) {
    const here = conceptRels.filter((p) => dirname(p) === (d || "."));
    const subdirs = [...dirs].filter((x) => x !== d && dirname(x) === (d || "."));
    const body = [
      `# ${escLabel(d ? basename(d) : basename(vaultAbs))}`,
      "",
      ...subdirs.sort().map((s) => `- [${escLabel(basename(s))}/](${encPath(basename(s))}/index.md)`),
      ...here.sort().map((p) => `- [${escLabel(basename(p, ".md"))}](${encPath(basename(p))})`),
      "",
    ].join("\n");
    const text = d === ""
      ? dumpFrontmatter({ okf_version: OKF_VERSION, ...(starId ? { [STAR_ID_KEY]: starId } : {}) }, body)
      : body;
    const dst = join(buildDir, d, "index.md");
    mkdirSync(dirname(dst), { recursive: true });
    writeFileSync(dst, text);
    indexes++;
  }
  return { concepts, indexes, warnings };
}
